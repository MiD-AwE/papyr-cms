<?php
declare(strict_types=1);

namespace Papyr\Core;

/*
 * Resolves and verifies the admin secret through one converged path,
 * regardless of which source supplied it:
 *
 *   1. Env var PAPYR_ADMIN_PASS — checked via getenv(), $_SERVER, and $_ENV,
 *      first non-empty wins. Plaintext, compared with hash_equals().
 *      Some hosts (notably PHP-FPM/LiteSpeed under Apache's SetEnv) only
 *      populate one of these three stores, so all three are checked rather
 *      than assuming getenv() alone reflects what the host actually set.
 *
 *   2. Config file secret.php (git-ignored, in the site's _config/ — see SiteConfig) —
 *      holds a password_hash() output, compared with password_verify().
 *      This is the portable fallback for hosts that don't cooperate with
 *      env vars at all.
 *
 *   3. Neither present — verify() always returns false. Callers use
 *      source() to show a setup message without revealing which store
 *      was checked or what it contained.
 *
 * Env var wins when both are present — it's the more explicit, deploy-time
 * choice (Docker, VPS, systemd units), so it should never be silently
 * shadowed by a leftover config file.
 */
class AdminAuth
{
    public static function secretFilePath(): string
    {
        return SiteConfig::path('secret.php');
    }

    public static function verify(string $submitted): bool
    {
        $env = self::envSecret();
        if ($env !== null) {
            return hash_equals($env, $submitted);
        }

        $hash = self::configHash();
        if ($hash !== null) {
            return password_verify($submitted, $hash);
        }

        return false;
    }

    /** 'env', 'config', or null — which source (if any) has a secret configured. */
    public static function source(): ?string
    {
        if (self::envSecret() !== null) return 'env';
        if (self::configHash() !== null) return 'config';
        return null;
    }

    /*
     * Hashes $plaintext and writes it to secretFilePath(). Used by the CLI
     * reset tool. Never called from a web-reachable path.
     */
    public static function writeSecretFile(string $plaintext, ?string $group = null): array
    {
        $php = "<?php\n"
            . "declare(strict_types=1);\n\n"
            . "// Generated by _papyr/bin/set-admin-pass.php — do not edit by hand.\n"
            . "// This file is git-ignored; it must never be committed.\n"
            . "return ['hash' => " . var_export(password_hash($plaintext, PASSWORD_DEFAULT), true) . "];\n";

        return SiteConfig::writeSecret('secret.php', $php, $group);
    }

    /*
     * Why the config-file secret can or cannot be used, for the login page:
     * 'ok' | 'missing' | 'unreadable' | 'invalid'. Env-var secrets are not
     * considered here — see source().
     */
    public static function configState(): string
    {
        return SiteConfig::secretState('secret.php');
    }

    private static function envSecret(): ?string
    {
        $val = getenv('PAPYR_ADMIN_PASS');
        if ($val !== false && $val !== '') {
            return $val;
        }

        $val = $_SERVER['PAPYR_ADMIN_PASS'] ?? '';
        if ($val !== '') {
            return $val;
        }

        $val = $_ENV['PAPYR_ADMIN_PASS'] ?? '';
        if ($val !== '') {
            return $val;
        }

        return null;
    }

    private static function configHash(): ?string
    {
        return SiteConfig::secretHash('secret.php');
    }
}
