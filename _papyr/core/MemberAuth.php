<?php
declare(strict_types=1);

namespace Papyr\Core;

/*
 * Invite-only participant access — a second, lower-privilege role beside
 * AdminAuth. One shared invite password, handed out by invitation, unlocks
 * participant features (comments). It never grants admin rights.
 *
 * Secret storage mirrors AdminAuth:
 *   1. Env var PAPYR_INVITE_PASS (plaintext, hash_equals), or
 *   2. _papyr/config/invite.php (git-ignored, password_hash output),
 *      written by _papyr/bin/set-invite-pass.php.
 *
 * Rotation: the session stores a fingerprint of the current secret.
 * Changing the invite password changes the fingerprint, so everyone
 * who unlocked with the old one is locked out on their next request.
 *
 * Brute force: failed attempts are counted per client IP in
 * _papyr/cache/throttle/ with an increasing lockout.
 */
class MemberAuth
{
    private const SESSION_FLAG = 'papyr_member';
    private const SESSION_VER  = 'papyr_member_ver';
    private const SESSION_NAME = 'papyr_member_name';
    private const SESSION_CSRF = 'papyr_csrf';

    private const FREE_ATTEMPTS = 5;     // failures before lockout begins
    private const BASE_LOCK_SEC = 60;    // first lockout length, doubles after

    public static function secretFilePath(): string
    {
        return __DIR__ . '/../config/invite.php';
    }

    /* ---------------- secret ---------------- */

    public static function configured(): bool
    {
        return self::envSecret() !== null || self::configHash() !== null;
    }

    public static function verify(string $submitted): bool
    {
        $env = self::envSecret();
        if ($env !== null) return hash_equals($env, $submitted);
        $hash = self::configHash();
        if ($hash !== null) return password_verify($submitted, $hash);
        return false;
    }

    /** Short, non-reversible fingerprint of whichever secret is active. */
    public static function fingerprint(): string
    {
        $basis = self::envSecret() !== null
            ? 'env:' . hash('sha256', (string) self::envSecret())
            : 'cfg:' . (string) self::configHash();
        return substr(hash('sha256', $basis), 0, 16);
    }

    public static function writeSecretFile(string $plaintext): void
    {
        $hash = password_hash($plaintext, PASSWORD_DEFAULT);
        $path = self::secretFilePath();
        $dir  = dirname($path);
        if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new \RuntimeException("MemberAuth: could not create {$dir}");
        }
        $php = "<?php\n"
            . "declare(strict_types=1);\n\n"
            . "// Generated by _papyr/bin/set-invite-pass.php — do not edit by hand.\n"
            . "// This file is git-ignored; it must never be committed.\n"
            . "return ['hash' => " . var_export($hash, true) . "];\n";
        if (file_put_contents($path, $php) === false) {
            throw new \RuntimeException("MemberAuth: could not write {$path}");
        }
        chmod($path, 0644); // readable by the web server user (e.g. XAMPP daemon); holds only a hash
    }

    /* ---------------- session ---------------- */

    /** True when this session unlocked with the CURRENT invite secret. Admins count too. */
    public static function isMember(): bool
    {
        if (($_SESSION['papyr_admin'] ?? false) === true) return true;
        if (($_SESSION[self::SESSION_FLAG] ?? false) !== true) return false;
        if (!self::configured()) return false;
        return hash_equals(self::fingerprint(), (string) ($_SESSION[self::SESSION_VER] ?? ''));
    }

    public static function grant(): void
    {
        session_regenerate_id(true);
        $_SESSION[self::SESSION_FLAG] = true;
        $_SESSION[self::SESSION_VER]  = self::fingerprint();
        $_SESSION[self::SESSION_CSRF] = bin2hex(random_bytes(16));
    }

    public static function revoke(): void
    {
        unset($_SESSION[self::SESSION_FLAG], $_SESSION[self::SESSION_VER], $_SESSION[self::SESSION_NAME]);
    }

    public static function csrfToken(): string
    {
        if (empty($_SESSION[self::SESSION_CSRF])) {
            $_SESSION[self::SESSION_CSRF] = bin2hex(random_bytes(16));
        }
        return (string) $_SESSION[self::SESSION_CSRF];
    }

    public static function checkCsrf(?string $token): bool
    {
        $have = (string) ($_SESSION[self::SESSION_CSRF] ?? '');
        return $have !== '' && is_string($token) && hash_equals($have, $token);
    }

    public static function displayName(): string
    {
        return (string) ($_SESSION[self::SESSION_NAME] ?? '');
    }

    public static function setDisplayName(string $name): void
    {
        $_SESSION[self::SESSION_NAME] = $name;
    }

    /* ---------------- throttle ---------------- */

    /** Seconds the caller must still wait, 0 if allowed to try. */
    public static function lockedFor(string $ip): int
    {
        $s = self::throttleRead($ip);
        return max(0, (int) ($s['until'] ?? 0) - time());
    }

    public static function recordFailure(string $ip): void
    {
        $s = self::throttleRead($ip);
        $fails = (int) ($s['fails'] ?? 0) + 1;
        $until = 0;
        if ($fails >= self::FREE_ATTEMPTS) {
            $steps = $fails - self::FREE_ATTEMPTS;
            $until = time() + min(3600, self::BASE_LOCK_SEC * (2 ** min($steps, 6)));
        }
        self::throttleWrite($ip, ['fails' => $fails, 'until' => $until]);
    }

    public static function clearFailures(string $ip): void
    {
        $f = self::throttleFile($ip);
        if (is_file($f)) @unlink($f);
    }

    /* ---------------- internals ---------------- */

    private static function throttleFile(string $ip): string
    {
        return __DIR__ . '/../cache/throttle/' . hash('sha256', $ip) . '.json';
    }

    private static function throttleRead(string $ip): array
    {
        $f = self::throttleFile($ip);
        if (!is_file($f)) return [];
        $d = json_decode((string) file_get_contents($f), true);
        // Forget failures older than a day.
        if (is_array($d) && (filemtime($f) ?: 0) < time() - 86400) return [];
        return is_array($d) ? $d : [];
    }

    private static function throttleWrite(string $ip, array $data): void
    {
        $f = self::throttleFile($ip);
        if (!is_dir(dirname($f))) @mkdir(dirname($f), 0775, true);
        @file_put_contents($f, json_encode($data), LOCK_EX);
    }

    private static function envSecret(): ?string
    {
        foreach ([getenv('PAPYR_INVITE_PASS'), $_SERVER['PAPYR_INVITE_PASS'] ?? '', $_ENV['PAPYR_INVITE_PASS'] ?? ''] as $v) {
            if (is_string($v) && $v !== '') return $v;
        }
        return null;
    }

    private static function configHash(): ?string
    {
        $path = self::secretFilePath();
        if (!is_readable($path)) return null;
        // Drop a stale opcache copy if the file changed, so a rotated invite
        // password takes effect on the very next request (not after
        // opcache.revalidate_freq seconds). No-op when the file is unchanged.
        if (function_exists('opcache_invalidate')) @opcache_invalidate($path, false);
        $data = require $path;
        $hash = is_array($data) ? ($data['hash'] ?? null) : null;
        return (is_string($hash) && $hash !== '') ? $hash : null;
    }
}
